export const CHARLES_MARKET_FOODS = FOODS.filter((food) => food.locationId === "charles-market");

export function searchFoods(query = "", locationId = "all") {
  const normalized = query.trim().toLowerCase();
  return FOODS.filter((food) => {
    const matchesQuery = !normalized || [food.name, food.description, ...food.tags].join(" ").toLowerCase().includes(normalized);
    const matchesLocation = locationId === "all" || food.locationId === locationId;
    return matchesQuery && matchesLocation;
  });
}
